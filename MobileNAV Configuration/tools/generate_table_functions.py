#!/usr/bin/env python3
"""Generate the table function codeunits from MobileNAV and Base Application symbols.

    python3 tools/generate_table_functions.py <MobileNAV .app> <Base Application .app>

Writes three codeunits under src/Functions and src/Preview:
- MNTableFunctions.Codeunit.al (77707): one record-bound procedure per table that a MobileNAV
  device page shows but MobileNAV Page Functions has no dispatcher for. Each raises the router's
  OnPageFunction, so a Button() on those pages needs no codeunit of its own.
- MNPageFunctionCatalog.Codeunit.al (77708): the record-bound procedures MobileNAV Page Functions
  has per table, used to reject a FunctionName() the companion cannot run.
- Preview/MNPreviewSubscribers.Codeunit.al (77712): manual subscribers on every MobileNAV table that
  hand each change to "BJF MN Preview Recorder" while an apply preview runs.

The committed output comes from MobileNAV 12.0.0.46 (the .app in the WMS app's .alpackages) and
Base Application 28.3.52162.53725. Run it again after a MobileNAV upgrade and commit the result.
The catalog codeunit also records that MobileNAV build in VerifiedMobileNAVVersion(), which the
"MobileNAV Version" Doctor check compares with the installed app. Verified builds: 12.0.0.45 to
12.0.0.49 (the generated output is identical for all five).
"""
import json
import pathlib
import re
import sys
import zipfile
import io

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "Functions"
# MobileNAV pages that carry [ServiceEnabled] wrappers of their own route through MobileNAV code
# this generator does not know, so their tables keep MobileNAV's companion.
MOBILENAV_TABLE_RANGE = range(42012800, 42013200)
KEEP_MOBILENAV_TABLES = {"MobileNAV Temporary Data", "MobileNAV Tracking Spec."}


def symbols(app_path):
    raw = pathlib.Path(app_path).read_bytes()
    start = raw.find(b"PK\x03\x04")
    with zipfile.ZipFile(io.BytesIO(raw[start:])) as z:
        text = z.read("SymbolReference.json").decode("utf-8-sig")
    return json.JSONDecoder().raw_decode(text)[0]


def walk(node, path=""):
    for kind in ("Pages", "Codeunits", "Tables"):
        for obj in node.get(kind, []):
            yield kind, obj, path
    for ns in node.get("Namespaces", []):
        yield from walk(ns, (path + "." if path else "") + ns.get("Name", ""))


def prop(obj, name):
    for p in obj.get("Properties", []):
        if p["Name"] == name:
            return p["Value"]
    return None


def is_service_enabled(method):
    return any(a["Name"] == "ServiceEnabled" for a in method.get("Attributes", []))


def main(mobilenav_app, base_app):
    mn = symbols(mobilenav_app)
    base = symbols(base_app)
    tables = {}
    for src in (base, mn):
        for kind, obj, path in walk(src):
            if kind == "Tables":
                tables[int(obj["Id"])] = (obj["Name"], path)

    page_functions = next(o for k, o, _ in walk(mn) if k == "Codeunits" and o["Name"] == "MobileNAV Page Functions")
    catalog = {}
    for method in page_functions["Methods"]:
        params = method.get("Parameters", [])
        if method["Name"].startswith("On") or not params or params[0].get("Name") != "Key":
            continue
        table = params[0]["TypeDefinition"]["Subtype"]["Name"]
        catalog.setdefault(table, []).append(method["Name"])

    targets = {}
    wrapped = set()
    for kind, obj, _ in walk(mn):
        if kind != "Pages" or not obj["Name"].startswith("MobileNAV "):
            continue
        source = prop(obj, "SourceTable")
        if not source or int(source) not in tables:
            continue
        table_id = int(source)
        name, namespace = tables[table_id]
        if name in catalog:
            continue
        if table_id in MOBILENAV_TABLE_RANGE and name not in KEEP_MOBILENAV_TABLES:
            continue
        if any(is_service_enabled(m) for m in obj.get("Methods", [])):
            wrapped.add(table_id)
        targets.setdefault(table_id, (name, namespace, []))[2].append(obj["Name"])
    for table_id in wrapped:
        targets.pop(table_id, None)

    write_table_functions(targets)
    write_catalog(catalog, tables, mn["Version"])
    write_preview_subscribers(sorted(o["Name"] for k, o, _ in walk(mn) if k == "Tables"))
    print(f"{len(targets)} table functions, {sum(len(v) for v in catalog.values())} Page Functions names in {len(catalog)} tables")


def function_name(table_name):
    return "BJF" + re.sub(r"[^A-Za-z0-9]", "", table_name) + "Func"


def quoted(name):
    return name if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) else f'"{name}"'


def write_table_functions(targets):
    usings = sorted({ns for _, ns, _ in targets.values() if ns})
    lines = ["// Generated by tools/generate_table_functions.py from MobileNAV symbols. Do not edit by hand.",
             "namespace BradFullwood.MobileNAV.Configuration;", ""]
    lines += [f"using {ns};" for ns in usings] + [""]
    lines += [
        "/// <summary>",
        "/// The page-function companion for MobileNAV device pages whose table MobileNAV Page Functions",
        "/// does not serve. MobileNAV calls the procedure a button names on the codeunit registered under",
        "/// the page's service name, passing the record as Key. Each procedure here raises the router's",
        "/// OnPageFunction, so a Button() on these pages is handled like any other.",
        "/// </summary>",
        "codeunit 77707 \"BJF MN Table Functions\"",
        "{",
        "    Access = Public;",
        "",
    ]
    by_name = sorted(targets.items(), key=lambda kv: kv[1][0])
    for _, (name, _, pages) in by_name:
        lines += [
            f"    /// <summary>Button taps on {', '.join(pages)}.</summary>",
            "    /// <param name=\"Key\">The record the button was tapped on.</param>",
            "    /// <param name=\"PageName\">The MobileNAV service name of the page.</param>",
            "    /// <param name=\"FieldName\">The control name of the button.</param>",
            "    /// <param name=\"DeviceID\">The device that sent the tap.</param>",
            "    /// <returns>The field control text MobileNAV sends back to the device.</returns>",
            f"    procedure {function_name(name)}(\"Key\": Record {quoted(name)}; PageName: Text[100]; FieldName: Text[75]; DeviceID: Text[190]) FieldControl: Text",
            "    begin",
            "        exit(this.Raise(\"Key\", PageName, FieldName, DeviceID));",
            "    end;",
            "",
        ]
    lines += [
        "    /// <summary>The function name the companion has for a table, or false when it has none.</summary>",
        "    /// <param name=\"TableNo\">The source table number of the page.</param>",
        "    /// <param name=\"FunctionName\">The companion procedure name for the table.</param>",
        "    /// <returns>True when the table has a function name.</returns>",
        "    internal procedure TryGetFunctionName(TableNo: Integer; var FunctionName: Text[50]): Boolean",
        "    begin",
        "        if this.FunctionNames.Count() = 0 then",
        "            this.LoadFunctionNames();",
        "        exit(this.FunctionNames.Get(TableNo, FunctionName));",
        "    end;",
        "",
        "    local procedure LoadFunctionNames()",
        "    begin",
    ]
    for _, (name, _, _) in by_name:
        lines += [f"        this.FunctionNames.Add(Database::{quoted(name)}, '{function_name(name)}');"]
    lines += [
        "    end;",
        "",
        "    local procedure Raise(SourceRecord: Variant; PageName: Text[100]; FieldName: Text[75]; DeviceID: Text[190]) FieldControl: Text",
        "    var",
        "        FieldControlFactory: Codeunit \"MobileNAV Object Functions\";",
        "        FunctionRouter: Codeunit \"BJF MN Function Router\";",
        "        RecRef: RecordRef;",
        "    begin",
        "        RecRef.GetTable(SourceRecord);",
        "        FunctionRouter.RaiseFromCompanion(RecRef, PageName, FieldName, DeviceID, FieldControlFactory);",
        "        FieldControlFactory.FcGetAsText(SourceRecord, FieldControl);",
        "    end;",
        "",
        "    var",
        "        FunctionNames: Dictionary of [Integer, Text[50]];",
        "}",
    ]
    (OUT / "MNTableFunctions.Codeunit.al").write_text("\n".join(lines) + "\n")


def write_catalog(catalog, tables, mobilenav_version):
    ids = {name: (tid, ns) for tid, (name, ns) in tables.items()}
    present = sorted(t for t in catalog if t in ids)
    usings = sorted({ids[t][1] for t in present if ids[t][1]})
    lines = ["// Generated by tools/generate_table_functions.py from MobileNAV symbols. Do not edit by hand.",
             "namespace BradFullwood.MobileNAV.Configuration;", ""]
    lines += [f"using {ns};" for ns in usings] + [""]
    lines += [
        "/// <summary>The record-bound procedures MobileNAV Page Functions has, per source table.</summary>",
        "codeunit 77708 \"BJF MN Page Function Catalog\"",
        "{",
        "    Access = Internal;",
        "",
        "    /// <summary>The MobileNAV app version this catalog was generated from.</summary>",
        "    /// <returns>The version as major.minor.build.revision.</returns>",
        "    procedure VerifiedMobileNAVVersion(): Text",
        "    begin",
        f"        exit('{mobilenav_version}');",
        "    end;",
        "",
        "    /// <summary>Whether MobileNAV Page Functions can run the named procedure for the table.</summary>",
        "    /// <param name=\"TableNo\">The source table number of the page.</param>",
        "    /// <param name=\"FunctionName\">The procedure name to look for.</param>",
        "    /// <returns>True when MobileNAV Page Functions has the procedure for the table.</returns>",
        "    procedure Contains(TableNo: Integer; FunctionName: Text): Boolean",
        "    begin",
        "        exit(this.Names(TableNo).Split('|').Contains(FunctionName));",
        "    end;",
        "",
        "    /// <summary>The procedure names for the table, separated by |, empty when it has none.</summary>",
        "    /// <param name=\"TableNo\">The source table number of the page.</param>",
        "    /// <returns>The names separated by |, or an empty text.</returns>",
        "    procedure Names(TableNo: Integer) FunctionNames: Text",
        "    begin",
        "        if this.NamesByTable.Count() = 0 then",
        "            this.LoadNames();",
        "        if not this.NamesByTable.Get(TableNo, FunctionNames) then",
        "            exit('');",
        "        exit(FunctionNames);",
        "    end;",
        "",
        "    local procedure LoadNames()",
        "    begin",
    ]
    for t in present:
        lines += [f"        this.NamesByTable.Add(Database::{quoted(t)}, '{'|'.join(catalog[t])}');"]
    lines += ["    end;", "", "    var", "        NamesByTable: Dictionary of [Integer, Text];", "}"]
    (OUT / "MNPageFunctionCatalog.Codeunit.al").write_text("\n".join(lines) + "\n")


def write_preview_subscribers(table_names):
    lines = ["// Generated by tools/generate_table_functions.py from MobileNAV symbols. Do not edit by hand.",
             "namespace BradFullwood.MobileNAV.Configuration;", "",
             "/// <summary>",
             "/// Hands every change to a MobileNAV table to \"BJF MN Preview Recorder\" while an apply preview",
             "/// runs. Bound only for the preview, so the subscribers cost nothing otherwise.",
             "/// </summary>",
             "codeunit 77712 \"BJF MN Preview Subscribers\"",
             "{",
             "    Access = Internal;",
             "    EventSubscriberInstance = Manual;", ""]
    for name in table_names:
        t = quoted(name)
        lines += [
            f"    [EventSubscriber(ObjectType::Table, Database::{t}, OnAfterInsertEvent, '', false, false)]",
            f"    local procedure \"{name}_OnAfterInsertEvent\"(var Rec: Record {t})",
            "    begin",
            "        this.Recorder.Inserted(Rec);",
            "    end;", "",
            f"    [EventSubscriber(ObjectType::Table, Database::{t}, OnBeforeModifyEvent, '', false, false)]",
            f"    local procedure \"{name}_OnBeforeModifyEvent\"(var Rec: Record {t})",
            "    begin",
            "        this.Recorder.Changing(Rec);",
            "    end;", "",
            f"    [EventSubscriber(ObjectType::Table, Database::{t}, OnBeforeDeleteEvent, '', false, false)]",
            f"    local procedure \"{name}_OnBeforeDeleteEvent\"(var Rec: Record {t})",
            "    begin",
            "        this.Recorder.Changing(Rec);",
            "    end;", "",
            f"    [EventSubscriber(ObjectType::Table, Database::{t}, OnBeforeRenameEvent, '', false, false)]",
            f"    local procedure \"{name}_OnBeforeRenameEvent\"(var Rec: Record {t})",
            "    begin",
            "        this.Recorder.Renaming(Rec);",
            "    end;", "",
        ]
    lines += ["    var", "        Recorder: Codeunit \"BJF MN Preview Recorder\";", "}"]
    out = HERE.parent / "src" / "Preview"
    out.mkdir(exist_ok=True)
    (out / "MNPreviewSubscribers.Codeunit.al").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
